    /**
     * Run the database seeds.
     */
    public function run(): void
    {
        $locales = [
            'it' => $this->getItalianTranslations(),
            'en' => $this->getEnglishTranslations(),
            'de' => $this->getGermanTranslations(),
            'fr' => $this->getFrenchTranslations(),
        ];

        DB::transaction(function () use ($locales) {
            foreach ($locales as $locale => $translations) {
                $payload = [];
                $now = now();

                foreach ($translations as $key => $value) {
                    $payload[] = [
                        'tenant_id' => null,
                        'locale' => $locale,
                        'key' => $key,
                        'value' => $value,
                        'created_at' => $now,
                        'updated_at' => $now,
                    ];
                }

                // Batch upsert su (tenant_id, locale, key) aggiornando solo il value
                foreach (array_chunk($payload, 100) as $chunk) {
                    Translation::upsert(
                        $chunk,
                        ['tenant_id', 'locale', 'key'],
                        ['value', 'updated_at']
                    );
                }
            }
        });
    }

