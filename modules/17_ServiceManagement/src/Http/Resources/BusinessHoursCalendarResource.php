<?php

declare(strict_types=1);

namespace Modules\ServiceManagement\Http\Resources;

use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\JsonResource;
use Modules\ServiceManagement\Models\BusinessHoursCalendar;

/**
 * @mixin BusinessHoursCalendar
 */
final class BusinessHoursCalendarResource extends JsonResource
{
    /**
     * @return array<string, mixed>
     */
    public function toArray(Request $request): array
    {
        return [
            'id' => $this->id,
            'code' => $this->code,
            'name' => $this->name,
            'timezone' => $this->timezone,
            'weekly_schedule' => $this->weekly_schedule ?? (object) [],
            'holidays' => $this->holidays ?? [],
            'hr_holiday_calendar_id' => $this->hr_holiday_calendar_id,
            'is_active' => (bool) $this->is_active,
            'created_at' => $this->created_at?->toIso8601String(),
        ];
    }
}
