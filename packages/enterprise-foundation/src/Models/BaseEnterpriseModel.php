<?php

declare(strict_types=1);

namespace Enterprise\Foundation\Models;

use Enterprise\Foundation\Concerns\AiEnabled;
use Enterprise\Foundation\Concerns\Auditable;
use Enterprise\Foundation\Concerns\EventAware;
use Enterprise\Foundation\Concerns\FeatureAware;
use Enterprise\Foundation\Concerns\HasUuidV7;
use Enterprise\Foundation\Concerns\WorkflowAware;
use Enterprise\MultiTenant\Concerns\BelongsToTenant;
use Illuminate\Database\Eloquent\Factories\Factory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;
use Illuminate\Support\Str;

/**
 * @property string $id
 * @property string|null $tenant_id Null only for global records of models that allow them (see BelongsToTenant).
 * @property Carbon|null $created_at
 * @property Carbon|null $updated_at
 */
abstract class BaseEnterpriseModel extends Model
{
    use AiEnabled,
        Auditable,
        BelongsToTenant,
        EventAware,
        FeatureAware,
        HasFactory,
        HasUuidV7,
        SoftDeletes,
        WorkflowAware;

    protected $keyType = 'string';

    public $incrementing = false;

    protected $guarded = ['id', 'created_at', 'updated_at', 'deleted_at'];

    public function __construct(array $attributes = [])
    {
        if (! isset($attributes['id'])) {
            $attributes['id'] = (string) Str::uuid7();
        }

        parent::__construct($attributes);

        $this->attributes['id'] = $attributes['id'];
    }

    /**
     * `id` is guarded, so `Model::create(['id' => $id, ...])` would keep the id generated by the constructor and silently drop
     * the one the caller chose (and already stored in related rows, such as the cost layers of a stock movement). A new
     * instance keeps an explicit id; an existing record never changes its id (see setAttribute).
     *
     * @param  array<string, mixed>  $attributes
     * @param  bool  $exists
     * @return static
     */
    public function newInstance($attributes = [], $exists = false)
    {
        $model = parent::newInstance($attributes, $exists);

        if (! $exists && isset($attributes['id']) && is_string($attributes['id'])) {
            $model->forceFill(['id' => $attributes['id']]);
        }

        return $model;
    }

    public function setAttribute($key, $value)
    {
        if ($key === $this->getKeyName() && $this->exists && ! empty($this->getAttributeFromArray($key))) {
            return $this;
        }

        return parent::setAttribute($key, $value);
    }

    public function getIncrementing(): bool
    {
        return false;
    }

    /**
     * Create a new factory instance for the enterprise model.
     *
     * A `#[UseFactory]` attribute or a `$factory` property wins. Otherwise the factory named after the class basename is
     * used, but only when it builds this very model: modules reuse short names (`Shift`, `Attendance`, `FeePlan`), and a
     * factory of a namesake in another module must not be picked up.
     *
     * @return Factory<static>|null
     */
    protected static function newFactory()
    {
        if (isset(static::$factory)) {
            return static::$factory::new();
        }

        $declared = static::getUseFactoryAttribute();

        if ($declared !== null) {
            return $declared;
        }

        $factoryName = 'Database\\Factories\\'.class_basename(static::class).'Factory';
        if (class_exists($factoryName)) {
            /** @var Factory<static> $factory */
            $factory = $factoryName::new();

            return $factory->modelName() === static::class ? $factory : null;
        }

        return null;
    }
}
