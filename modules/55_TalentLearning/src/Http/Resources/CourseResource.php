<?php

declare(strict_types=1);

namespace Modules\TalentLearning\Http\Resources;

use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\JsonResource;
use Modules\TalentLearning\Models\LmsCourse;

/**
 * A course of the catalogue.
 *
 * @mixin LmsCourse
 */
final class CourseResource extends JsonResource
{
    /**
     * @return array<string, mixed>
     */
    public function toArray(Request $request): array
    {
        return [
            'id' => $this->id,
            'code' => $this->code,
            'title' => $this->title,
            'description' => $this->description,
            'delivery' => $this->delivery,
            'duration_hours' => $this->duration_hours,
            'is_mandatory' => $this->is_mandatory,
            'validity_months' => $this->validity_months,
            'pass_score' => $this->pass_score,
            'status' => $this->status,
            'created_at' => $this->created_at?->toIso8601String(),
            'updated_at' => $this->updated_at?->toIso8601String(),
        ];
    }
}
